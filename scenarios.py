# Private, machine-local practice packs live under the Git-ignored data directory.
def load_local_scenarios():
    import json
    from pathlib import Path
    path = Path(__file__).resolve().parent / 'data' / 'local-scenarios.json'
    if not path.exists():
        return []
    extra = json.loads(path.read_text(encoding='utf-8'))
    if not isinstance(extra, list):
        raise ValueError('Local scenarios must be a list')
    ids = {s['id'] for s in SCENARIOS}
    for case in extra:
        if not isinstance(case, dict) or not all(k in case for k in SCENARIOS[0]):
            raise ValueError('Local scenario is missing required fields')
        if case['id'] in ids:
            raise ValueError('Duplicate local scenario ID')
        ids.add(case['id'])
    return extra


SCENARIOS = load_local_scenarios() + SCENARIOS


def scenario_by_id(scenario_id):
    return next((s for s in SCENARIOS if s["id"] == scenario_id), None)


def public_scenario(scenario):
    return {k: v for k, v in scenario.items() if k != "facts"}
